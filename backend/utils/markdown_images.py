"""Markdown 图片引用的共享匹配模式。

解析产物里的图片路径由上传文件名派生，常含半角括号（浏览器/微信重复下载的
"(1)""(2)" 后缀、人工命名的"(第3版)"等）。CommonMark 行内链接目标允许成对
平衡括号；旧的 ``([^)]+)`` 会在路径内第一个 ``)`` 处把 src 截断（例如
``好猫项目(3)(2)_images/image_1.png`` 被截成 ``好猫项目(3``），导致证据块
图片哈希缺失、段落文本残留路径碎片、前端图片改写与 agent 取图失效。

``IMAGE_SRC`` 先按"非括号字符 + 一层成对括号"匹配完整 src；括号不平衡时
回退 ``[^)]*`` 截断语义，保持对畸形内容的旧有容错。
"""

from __future__ import annotations

import re

#: 图片 src 片段（允许一层成对括号，含空格；不平衡时回退旧截断行为）
IMAGE_SRC = r"(?:[^()]|\([^()]*\))+|[^)]*"

#: 同上，但沿用旧行为不允许空白（供行锚定的整行图片模式使用）
IMAGE_SRC_NO_WS = r"(?:[^()\s]|\([^()\s]*\))+|[^)\s]*"

#: 完整图片引用：group(1)=alt 文本，group(2)=完整 src
IMAGE_REF_RE = re.compile(r"!\[([^\]]*)\]\((" + IMAGE_SRC + r")\)")
